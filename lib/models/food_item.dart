class FoodItem {
  final String code;
  final String name;
  final double calories;
  final double protein;
  final double lipids;
  final double carbs;
  final double fiber;

  FoodItem({
    required this.code,
    required this.name,
    required this.calories,
    required this.protein,
    required this.lipids,
    required this.carbs,
    required this.fiber,
  });
}